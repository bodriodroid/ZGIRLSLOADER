#!/usr/bin/env python3
"""Rasterises the Oswald font (SIL Open Font License 1.1, tools/fonts/) into src/app/credits_font.h: a small embedded
glyph set (Basic Latin + Latin-1 + a few typographic marks) used for the message at the end of the credits roll.
No font library is needed at run time.   usage: python3 tools/gen_credits_font.py [weight 200..700] [px]"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

weight = int(sys.argv[1]) if len(sys.argv) > 1 else 500
px = int(sys.argv[2]) if len(sys.argv) > 2 else 48
here = os.path.dirname(os.path.abspath(__file__))
font = ImageFont.truetype(os.path.join(here, "fonts", "Oswald-VariableFont_wght.ttf"), px)
font.set_variation_by_axes([weight])

cps = list(range(0x20, 0x7F)) + list(range(0xA1, 0x100)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2022]
glyphs, blob = [], bytearray()
for cp in cps:
    ch = chr(cp)
    adv = font.getlength(ch)
    l, t, r, b = font.getbbox(ch, anchor="ls")          # relative to the pen position on the baseline
    w, h = max(0, r - l), max(0, b - t)
    off = len(blob)
    if w and h:
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor="ls")
        blob += im.tobytes()
    glyphs.append((cp, w, h, l, t, adv, off))

rle = bytearray()
i = 0
while i < len(blob):
    v = blob[i]
    if v == 0:
        n = 1
        while i + n < len(blob) and blob[i + n] == 0 and n < 255:
            n += 1
        rle += bytes([0, n]); i += n
    else:
        rle.append(v); i += 1

asc, desc = font.getmetrics()
out = ["// credits_font.h - GENERATED by tools/gen_credits_font.py from Oswald (SIL Open Font License 1.1), weight %d, %d px." % (weight, px),
       "// Glyph bitmaps (8-bit coverage, zero-run encoded) for the message at the end of the credits roll.  Do not edit.",
       "#pragma once", "#include <cstdint>", "",
       "namespace zengine {", "namespace credits {", "namespace oswald {", "",
       "struct Glyph { uint32_t cp; int16_t w, h, xo, yo; float adv; uint32_t off; };",
       "constexpr int kPx = %d, kAscent = %d, kDescent = %d;" % (px, asc, desc),
       "constexpr uint32_t kRawSize = %d;" % len(blob),
       "static const Glyph kGlyphs[] = {"]
for g in glyphs:
    out.append("    {0x%X, %d, %d, %d, %d, %.2ff, %d}," % g)
out += ["};", "static const uint8_t kRle[] = {"]
for k in range(0, len(rle), 32):
    out.append("    " + ",".join(str(x) for x in rle[k:k + 32]) + ",")
out += ["};", "", "}  // namespace oswald", "}  // namespace credits", "}  // namespace zengine", ""]
dst = os.path.join(here, "..", "src", "app", "credits_font.h")
open(dst, "w").write("\n".join(out))
print("glyphs", len(glyphs), "raw", len(blob), "rle", len(rle), "->", dst)
