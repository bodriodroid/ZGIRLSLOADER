#!/usr/bin/env python3
"""Rasterises DSEG7 Classic Bold (SIL Open Font License 1.1, tools/fonts/DSEG7Classic-Bold.ttf, (c) 2017 keshikan) into
src/app/seg_font.h: the seven-segment glyphs (Basic Latin 0x20..0x7E) for the error-code display and the RAM readout.
No font library is needed at run time.   usage: python3 tools/gen_seg_font.py [px]

The generated bitmaps are a derivative of the font: they are NOT called DSEG, and the licence text travels with the font file
(tools/fonts/DSEG-LICENSE.txt) and in THIRD_PARTY_NOTICES.md."""
import sys, os
from PIL import Image, ImageDraw, ImageFont

px = int(sys.argv[1]) if len(sys.argv) > 1 else 64
here = os.path.dirname(os.path.abspath(__file__))
font = ImageFont.truetype(os.path.join(here, "fonts", "DSEG7Classic-Bold.ttf"), px)

cps = list(range(0x20, 0x7F))
glyphs, blob = [], bytearray()
for cp in cps:
    ch = chr(cp)
    adv = font.getlength(ch)
    l, t, r, b = font.getbbox(ch, anchor="ls")
    w, h = max(0, r - l), max(0, b - t)
    off = len(blob)
    if w and h:
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor="ls")
        blob += im.tobytes()
    glyphs.append((cp, w, h, l, t, adv, off))

rle = bytearray()
i = 0
while i < len(blob):
    v = blob[i]
    if v == 0:
        n = 1
        while i + n < len(blob) and blob[i + n] == 0 and n < 255:
            n += 1
        rle += bytes([0, n]); i += n
    else:
        rle.append(v); i += 1

asc, desc = font.getmetrics()
out = ["// seg_font.h - GENERATED by tools/gen_seg_font.py from DSEG7 Classic Bold by keshikan (SIL Open Font License 1.1), %d px." % px,
       "// Seven-segment glyph bitmaps (8-bit coverage, zero-run encoded) for the error-code display and the RAM readout.  Do not edit.",
       "// Licence: tools/fonts/DSEG-LICENSE.txt.  This derived bitmap set is not called DSEG (reserved font name).",
       "#pragma once", "#include <cstdint>", "",
       "namespace zengine {", "namespace segfont {", "",
       "struct Glyph { uint32_t cp; int16_t w, h, xo, yo; float adv; uint32_t off; };",
       "constexpr int kPx = %d, kAscent = %d, kDescent = %d;" % (px, asc, desc),
       "constexpr uint32_t kRawSize = %d;" % len(blob),
       "static const Glyph kGlyphs[] = {"]
for g in glyphs:
    out.append("    {0x%X, %d, %d, %d, %d, %.2ff, %d}," % g)
out += ["};", "static const uint8_t kRle[] = {"]
for k in range(0, len(rle), 32):
    out.append("    " + ",".join(str(x) for x in rle[k:k + 32]) + ",")
out += ["};", "", "}  // namespace segfont", "}  // namespace zengine", ""]
dst = os.path.join(here, "..", "src", "app", "seg_font.h")
open(dst, "w").write("\n".join(out))
print("glyphs", len(glyphs), "raw", len(blob), "rle", len(rle), "asc", asc, "desc", desc, "->", dst)
