#!/usr/bin/env python3
"""Packs the loader's start-up logo (android/branding/boot_logo.png: white line art on a transparent 1600x900 canvas) into
src/app/boot_logo.h, so the app needs no image library: the alpha plane is cropped to the drawing, cut to 4 bits and run-length coded
(a byte = level<<4 | run, run 1..14, 15 = "15 + the varint that follows"), then written as base64; the few coloured pixels (the little
face) travel as a raw RGBA patch.   usage: python3 tools/gen_boot_logo.py [in.png] [out.h]"""
import base64, os, sys
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "android", "branding", "boot_logo.png")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "src", "app", "boot_logo.h")
im = Image.open(src).convert("RGBA")
cw, ch = im.size
bbox = im.getchannel("A").getbbox()
x0, y0, x1, y1 = bbox
w, h = x1 - x0, y1 - y0
px = im.load()

# the coloured pixels (everything the white tint would lose): a rectangle of raw RGBA
cx0 = cy0 = 10**9
cx1 = cy1 = -1
for y in range(y0, y1):
    for x in range(x0, x1):
        r, g, b, a = px[x, y]
        if a > 8 and min(r, g, b) < 240:
            cx0, cy0, cx1, cy1 = min(cx0, x), min(cy0, y), max(cx1, x + 1), max(cy1, y + 1)
face = bytearray()
for y in range(cy0, cy1):
    for x in range(cx0, cx1):
        face += bytes(px[x, y])

out = bytearray()
def put(level, run):
    while run > 0:
        if run <= 14:
            out.append(level << 4 | run); return
        extra = run - 15
        out.append(level << 4 | 15)
        while True:
            b = extra & 0x7F; extra >>= 7
            out.append(b | (0x80 if extra else 0))
            if not extra: break
        return
cur, run = None, 0
for y in range(y0, y1):
    for x in range(x0, x1):
        a = px[x, y][3]
        lvl = (a * 15 + 127) // 255
        if lvl == cur: run += 1
        else:
            if run: put(cur, run)
            cur, run = lvl, 1
put(cur, run)

def lit(name, data):
    b64 = base64.b64encode(bytes(data)).decode()
    lines = [b64[i:i + 112] for i in range(0, len(b64), 112)]
    return "inline constexpr char %s[] =\n%s;\n" % (name, "\n".join('    "%s"' % l for l in lines))

with open(dst, "w") as f:
    f.write("// boot_logo.h - GENERATED by tools/gen_boot_logo.py from android/branding/boot_logo.png; do not edit.\n")
    f.write("// The start-up logo: a %dx%d canvas, the drawing in the rectangle (%d,%d) %dx%d; coloured pixels in a RGBA patch.\n" % (cw, ch, x0, y0, w, h))
    f.write("#pragma once\n\nnamespace zengine::bootlogo {\n\n")
    f.write("inline constexpr int kCanvasW = %d, kCanvasH = %d;\n" % (cw, ch))
    f.write("inline constexpr int kX = %d, kY = %d, kW = %d, kH = %d;\n" % (x0, y0, w, h))
    f.write("inline constexpr int kPatchX = %d, kPatchY = %d, kPatchW = %d, kPatchH = %d;\n\n" % (cx0, cy0, cx1 - cx0, cy1 - cy0))
    f.write(lit("kAlphaB64", out))
    f.write("\n")
    f.write(lit("kPatchB64", face))
    f.write("\n}  // namespace zengine::bootlogo\n")
print("alpha rle", len(out), "bytes; patch", len(face), "bytes ->", dst, os.path.getsize(dst), "bytes of source")
