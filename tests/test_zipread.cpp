static void save(const fs::path& p, const uint8_t* b, size_t n) {
    std::ofstream f(p, std::ios::binary | std::ios::trunc);
    f.write(reinterpret_cast<const char*>(b), static_cast<std::streamsize>(n));
}
static std::string slurp(const fs::path& p) {
    std::ifstream f(p, std::ios::binary);
    return std::string(std::istreambuf_iterator<char>(f), {});
}

int main() {
    const fs::path dir = fs::temp_directory_path() / ("zg_zip_test_" + std::to_string(std::rand()));
    fs::remove_all(dir);
    fs::create_directories(dir);
    std::string err;

    // ---- inflate on its own
    {
        std::vector<uint8_t> out;
        const uint8_t stored[] = {0x01, 0x03, 0x00, 0xFC, 0xFF, 'a', 'b', 'c'};   // one final stored block "abc"
        CHECK(zipread::inflate(stored, sizeof stored, out, 100, &err) && std::string(out.begin(), out.end()) == "abc");
        const uint8_t fixedHi[] = {0xcb, 0x48, 0xcd, 0xc9, 0xc9, 0x07, 0x00};      // fixed Huffman "hello"
        CHECK(zipread::inflate(fixedHi, sizeof fixedHi, out, 100, &err) && std::string(out.begin(), out.end()) == "hello");
        CHECK(!zipread::inflate(fixedHi, sizeof fixedHi, out, 3, &err) && !err.empty());                  // larger than allowed
        CHECK(!zipread::inflate(fixedHi, 3, out, 100, &err));                                              // cut off
        const uint8_t bad[] = {0x07, 0xff, 0xff};                                                          // block type 3
        CHECK(!zipread::inflate(bad, sizeof bad, out, 100, &err));
        CHECK(zipread::crc32(reinterpret_cast<const uint8_t*>("123456789"), 9) == 0xCBF43926u);
    }

    // ---- a zip with a wrapper folder, a directory entry, a stored file, an empty file, a macOS junk entry
    save(dir / "wrapped.zip", kZipWrapped, sizeof kZipWrapped);
    std::vector<zipread::Entry> es;
    CHECK(zipread::list((dir / "wrapped.zip").string(), es, &err) && es.size() == 7);
    bool sawDeflate = false, sawStored = false;
    for (const auto& e : es) {
        if (e.name == "wrap-master/characters/a.txt") {
            sawDeflate = e.method == 8 && e.usize == 2620 && e.crc == 0xad6b3f77u;
            std::vector<uint8_t> data;
            CHECK(zipread::read((dir / "wrapped.zip").string(), e, data, &err) && data.size() == 2620 && zipread::crc32(data.data(), data.size()) == 0xad6b3f77u);
        }
        if (e.name == "wrap-master/b.bin") sawStored = e.method == 0 && e.usize == 300;
    }
    CHECK(sawDeflate && sawStored);
    zipread::ExtractStats st;
    CHECK(zipread::extract((dir / "wrapped.zip").string(), (dir / "w1").string(), st, true, &err));
    CHECK(st.strippedFolder == "wrap-master" && st.files == 5 && st.problems.empty());
    CHECK(fs::exists(dir / "w1" / "mod.ini") && fs::exists(dir / "w1" / "characters" / "a.txt") && fs::file_size(dir / "w1" / "characters" / "a.txt") == 2620);
    CHECK(slurp(dir / "w1" / "hello.txt") == "hello hello hello hello" && fs::file_size(dir / "w1" / "empty.txt") == 0 && fs::file_size(dir / "w1" / "b.bin") == 300);
    CHECK(!fs::exists(dir / "w1" / "__MACOSX") && !fs::exists(dir / "w1" / "wrap-master"));
    CHECK(zipread::extract((dir / "wrapped.zip").string(), (dir / "w2").string(), st, false, &err) && st.strippedFolder.empty() && fs::exists(dir / "w2" / "wrap-master" / "mod.ini"));

    // ---- a damaged byte is caught by the CRC; the rest still extracts
    {
        std::vector<uint8_t> dmg(kZipWrapped, kZipWrapped + sizeof kZipWrapped);
        size_t at = 0;
        for (size_t i = 0; i + 4 < dmg.size(); ++i)   // the stored b.bin: its bytes follow its local header name
            if (dmg[i] == 'b' && dmg[i + 1] == '.' && dmg[i + 2] == 'b' && dmg[i + 3] == 'i' && dmg[i + 4] == 'n') {
                at = i + 5 + 20;
                break;
            }
        CHECK(at > 0);
        dmg[at] ^= 0xFF;
        save(dir / "dmg.zip", dmg.data(), dmg.size());
        CHECK(zipread::extract((dir / "dmg.zip").string(), (dir / "d1").string(), st, true, &err));
        CHECK(st.problems.size() == 1 && st.problems[0].find("CRC") != std::string::npos && st.files == 4);
    }

    // ---- no wrapper (a file at the top) and a refused path
    save(dir / "mixed.zip", kZipMixed, sizeof kZipMixed);
    CHECK(zipread::extract((dir / "mixed.zip").string(), (dir / "sandbox" / "m").string(), st, true, &err));
    CHECK(st.strippedFolder.empty() && st.files == 2 && st.problems.size() == 1);
    CHECK(slurp(dir / "sandbox" / "m" / "x" / "y.txt") == "one" && slurp(dir / "sandbox" / "m" / "top.txt") == "two");
    CHECK(!fs::exists(dir / "sandbox" / "evil.txt") && !fs::exists(dir / "evil.txt"));

    // ---- a .zip dropped into mods/modscustom becomes a mod (modsdir.h)
    {
        const fs::path game = dir / "game";
        fs::create_directories(game / "mods" / "modscustom");
        // the sample zip holds a "b.bin": the mod check refuses native code, as it must (error 5).  Same-length rename for the mount test;
        // names are not part of the CRC.
        std::vector<uint8_t> ok(kZipWrapped, kZipWrapped + sizeof kZipWrapped);
        for (size_t i = 0; i + 5 <= ok.size(); ++i)
            if (ok[i] == 'b' && ok[i + 1] == '.' && ok[i + 2] == 'b' && ok[i + 3] == 'i' && ok[i + 4] == 'n') ok[i + 2] = 't', ok[i + 3] = 'x', ok[i + 4] = 't';
        save(game / "mods" / "modscustom" / "wrapped.zip", ok.data(), ok.size());
        bool logged = false;
        {   // with the .bin in it the mod is listed but blocked (this first start also unpacks wrapped.zip)
            fs::create_directories(game / "mods" / "resourcepacks");
            save(game / "mods" / "resourcepacks" / "native.zip", kZipWrapped, sizeof kZipWrapped);
            Vfs vb;
            modsdir::Report rb = modsdir::mountAll(vb, game.string(), false);
            bool blocked = false;
            for (const auto& i : rb.items) blocked = blocked || (i.id == "native" && i.blocked && !i.mounted);
            CHECK(blocked);
            for (const auto& l : rb.log) logged = logged || l.find("unzipped wrapped.zip") != std::string::npos;
            fs::remove(game / "mods" / "resourcepacks" / "native.zip");
            fs::remove_all(game / "mods" / "resourcepacks" / "native");
        }
        Vfs vfs;
        modsdir::Report rep = modsdir::mountAll(vfs, game.string(), false);
        CHECK(fs::exists(game / "mods" / "modscustom" / "wrapped" / "mod.ini") && fs::exists(game / "mods" / "modscustom" / "wrapped" / ".zipsrc"));
        const modsdir::Item* it = nullptr;
        for (const auto& i : rep.items)
            if (i.kind == "mod" && i.id == "wrapped") it = &i;
        CHECK(it && it->name == "Wrapped" && it->version == "2" && it->mounted);
        std::string real;
        CHECK(vfs.resolve("characters/a.txt", &real));
        CHECK(logged);
        // a second start does not unpack it again
        Vfs vfs2;
        modsdir::Report rep2 = modsdir::mountAll(vfs2, game.string(), false);
        logged = false;
        for (const auto& l : rep2.log) logged = logged || l.find("unzipped") != std::string::npos;
        CHECK(!logged);
        // a folder of the same name that did not come from the zip is left alone, with a warning
        fs::create_directories(game / "mods" / "resourcepacks" / "mine");
        save(game / "mods" / "resourcepacks" / "mine.zip", kZipWrapped, sizeof kZipWrapped);
        Vfs vfs3;
        modsdir::Report rep3 = modsdir::mountAll(vfs3, game.string(), false);
        bool warned = false;
        for (const auto& w : rep3.warnings) warned = warned || w.find("mine.zip") != std::string::npos;
        CHECK(warned && !fs::exists(game / "mods" / "resourcepacks" / "mine" / "mod.ini"));
        // a zip that is not a zip: a warning, no folder
        save(game / "mods" / "stages" / "bad.zip", reinterpret_cast<const uint8_t*>("this is not a zip file at all, really not!!"), 42);
        Vfs vfs4;
        modsdir::Report rep4 = modsdir::mountAll(vfs4, game.string(), false);
        warned = false;
        for (const auto& w : rep4.warnings) warned = warned || w.find("bad.zip") != std::string::npos;
        CHECK(warned && !fs::exists(game / "mods" / "stages" / "bad"));
        // a mod inside a wrapper folder: its mod.ini is found one level down
        fs::create_directories(game / "mods" / "modscustom" / "outer" / "inner-master");
        std::ofstream(game / "mods" / "modscustom" / "outer" / "inner-master" / "mod.ini") << "name = Inner\nversion = 9\n";
        std::ofstream(game / "mods" / "modscustom" / "outer" / "inner-master" / "x.txt") << "x";
        Vfs vfs5;
        modsdir::Report rep5 = modsdir::mountAll(vfs5, game.string(), false);
        it = nullptr;
        for (const auto& i : rep5.items)
            if (i.id == "outer") it = &i;
        CHECK(it && it->name == "Inner" && it->version == "9");
    }

    // ---- not a zip / missing
    save(dir / "junk.zip", reinterpret_cast<const uint8_t*>("this is not a zip file at all, really not!!"), 42);
    CHECK(!zipread::list((dir / "junk.zip").string(), es, &err) && !err.empty());
    CHECK(!zipread::extract((dir / "missing.zip").string(), (dir / "z").string(), st, true, &err));

    fs::remove_all(dir);
    std::printf("zipread tests: %d checks, %d failed\n", g_checks, g_fail);
    return g_fail ? 1 : 0;
}
