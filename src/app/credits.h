// credits.h - ZGirls Loader: the credits roll and the "Thanks for playing" card, from the user's own game data.
//
//   text     ui/config/Credits/credits_2021.ini (Extras -> Credits; falls back to credits.ini), or credits_contrib_2013.ini
//            (Extras -> Contributors).  Format: "CreditsPage: <Intro|AllText|LeftImage|RightImage|TopImage|BottomImage>",
//            "Image: <texture>", "Credit: <name , role>" (the text may sit on the next line; "Blank" = an empty slot),
//            "Header:" (the winged title, two slots), '#' starts a comment.  A page that holds more than its slots spills
//            over: a left / right picture runs on beside the rest of the list, other layouts continue as plain text pages (the
//            contributors' list is one page of thousands of names in the file).
//   look     Credits.gbs: "Credits Names" / "Big Options w Wings" fonts, the header's wings, the 40 px slot grid of every
//            page layout, the roll's speed (CreditsScroll: 719 canvas px per 594 ticks, pages stacked 720 px apart).
//   end      ThanksForPlaying.gbs "ThanksForPlaying" (logo, the thanks.png picture, the title text and the fade), shown
//            after the roll when begin() asked for it (the end of a story).
//   note     after the last page, a closing message from the loader's author in Oswald (SIL OFL), drawn from the glyph set
//            embedded in credits_font.h (generated by tools/gen_credits_font.py); the roll stops on it for a few seconds.
// Tap = pause / resume ("Credits Paused - any button resumes."), the X button / Back leaves.  Nothing is bundled.
#pragma once
#include <SDL.h>

#include <string>
#include <unordered_map>
#include <vector>

#include "game_ui.h"
#include "gamedata.h"
#include "gbs_anim.h"
#include "menu_data.h"
#include "music_player.h"
#include "ui.h"

namespace zengine {
namespace credits {

struct Entry {
    enum class Kind { Blank, Credit, Header } kind = Kind::Blank;
    std::string name, title;   // Credit: "Name , Title" -> right / left column; no comma = centred in `name`
    bool centered = false;
    int slots() const { return kind == Kind::Header ? 2 : 1; }
};

struct Page {
    enum class Layout { Intro, AllText, LeftImage, RightImage, TopImage, BottomImage } layout = Layout::AllText;
    std::string image;          // texture name as written in the file ("" = none)
    std::vector<Entry> rows;
};

// Slots a page layout has (11 on the intro page, 12 with a top / bottom picture, 18 otherwise).
int slotCapacity(Page::Layout l);
// The file's text -> pages (overflow spills into AllText pages).  Pure function, used by the tests.
std::vector<Page> parseCredits(const std::string& text);

class CreditsScreen {
public:
    void setGameData(const GameData* gd);
    // The theme of the roll (and of the Thanks card): credits / ending themes of the data, else the menu's.
    void setMusic(MusicPlayer* m) { music_ = m; }
    // Restarts the roll.  contributors = the backers' file; thanks = finish with the Thanks for playing card.
    void begin(const std::string& lang, bool contributors, bool thanks);
    // false = the roll (and the card) is over or was closed.
    bool frame(Ui& ui, SDL_Renderer* r, int dtMs);
    bool onBack() { return false; }   // Back always leaves

    size_t pageCount() const { return pages_.size(); }

private:
    void bind(SDL_Renderer* r);
    void drawPage(const Page& pg, float oy);
    void drawThanks(Ui& ui, SDL_Renderer* r, bool& done, int steps);
    void ensureNoteFont();
    void drawNote(float oy);

    const GameData* gd_ = nullptr;
    MusicPlayer* music_ = nullptr;
    std::string lang_ = "en";
    Localization loc_;
    std::vector<Page> pages_;
    bool contributors_ = false, thanks_ = false;
    bool loaded_ = false;
    int tick_ = 0;
    double acc_ = 0;
    bool paused_ = false;
    int phase_ = 0;                 // 0 roll, 1 thanks card
    int thanksTick_ = 0;
    int holdTicks_ = 0;             // frames the pointer has been down (a short press pauses, a long one fast-forwards)

    GameUi gfx_;
    SDL_Renderer* ren_ = nullptr;
    bool gfxOk_ = false;
    const GbsScene* credScene_ = nullptr;
    const GbsSceneView* credView_ = nullptr;
    std::vector<GbsNode> headerTpl_;   // the "HeaderGRP" template (text + two wings), drawn once per header
    const GbsFont* fNames_ = nullptr;
    const GbsFont* fHead_ = nullptr;
    GbsAnimPlayer thanksAnim_;
    bool thanksBound_ = false;

    struct NoteGlyph {
        SDL_Texture* t = nullptr;
        int w = 0, h = 0, xo = 0, yo = 0;
        float adv = 0;
    };
    std::unordered_map<uint32_t, NoteGlyph> noteGlyphs_;
    bool noteFontTried_ = false;
};

}  // namespace credits
}  // namespace zengine
